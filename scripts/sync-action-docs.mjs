import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const sourceUrl = 'https://raw.githubusercontent.com/wot-ui/ci-action/main/README.md'
const publicUrl = 'https://github.com/wot-ui/ci-action#readme'
const args = process.argv.slice(2)
const check = args.includes('--check')
const sourceIndex = args.indexOf('--source')
if (sourceIndex !== -1 && (!args[sourceIndex + 1] || args[sourceIndex + 1].startsWith('--')))
  throw new Error('--source requires a local README path')
const allowed = new Set(['--check', '--source', ...(sourceIndex === -1 ? [] : [args[sourceIndex + 1]])])
if (args.some(arg => !allowed.has(arg)))
  throw new Error('Usage: node scripts/sync-action-docs.mjs [--check] [--source path/to/README.md]')

async function readSource() {
  if (sourceIndex !== -1)
    return readFile(path.resolve(args[sourceIndex + 1]), 'utf8')
  const response = await fetch(sourceUrl, { signal: AbortSignal.timeout(30000) })
  if (!response.ok)
    throw new Error(`Cannot fetch Action README: HTTP ${response.status}`)
  return response.text()
}

function headings(markdown) {
  let fence
  const found = []
  for (const line of markdown.split('\n')) {
    const delimiter = /^\s*(`{3,}|~{3,})/.exec(line)?.[1]
    if (delimiter) {
      if (!fence)
        fence = delimiter
      else if (delimiter[0] === fence[0] && delimiter.length >= fence.length)
        fence = undefined
      continue
    }
    if (!fence && /^#{1,6} /.test(line)) {
      found.push(line.replace(/^#+ /, '').replace(/[*`]/g, '').trim().toLowerCase()
        .replace(/[^\p{L}\p{N}\s_-]/gu, '').replace(/\s/g, '-'))
    }
  }
  return found
}

const source = (await readSource()).replaceAll('\r\n', '\n')
const markers = ['## AI 一键接入', '## 参数参考', '## 版本规则', '## 维护与发布']
const offsets = markers.map(marker => source.indexOf(`\n${marker}\n`))
if (offsets.some((offset, i) => offset < 0 || (i > 0 && offset <= offsets[i - 1])))
  throw new Error('Action README structure changed; update the sync section boundaries before generating docs')
const [start, parameters, versions, maintenance] = offsets
const guide = `${source.slice(start, parameters).trim()}\n\n${source.slice(versions, maintenance).trim()}`
// Promote parameter subsections so setting / preview appear in the site's TOC.
const reference = source.slice(parameters, versions).trim().replace(/^## 参数参考\n/, '').replace(/^(#{2,5}) /gm, (_, hashes) => `${hashes.slice(1)} `).trim()
const guideAnchors = new Set(headings(guide))
const referenceAnchors = new Set(headings(reference))
function rewrite(markdown, current) {
  return markdown.replace(/\]\(#([^)]*)\)/g, (_, fragment) => {
    const anchor = decodeURIComponent(fragment)
    const destination = anchor === '参数参考' || referenceAnchors.has(anchor)
      ? 'action-reference.md'
      : guideAnchors.has(anchor) ? 'github-action.md' : undefined
    if (!destination)
      throw new Error(`Unmapped Action README anchor: #${fragment}`)
    const hash = anchor === '参数参考' ? '' : `#${fragment}`
    return `](${destination === current && hash ? '' : destination}${hash})`
  })
}
const digest = createHash('sha256').update(source).digest('hex')
const banner = `<!-- Generated by pnpm docs:action:sync from ${publicUrl}; sha256=${digest}. Do not edit manually. -->`
const origin = `内容同步自 [wot-ui/ci-action README](${publicUrl})，与独立 Action 保持一致。`
const files = new Map([
  ['github-action.md', `# GitHub Action\n\n${banner}\n\n${origin}\n\n[AI 一键接入](#ai-一键接入) · [快速开始](#快速开始) · [示例 Demo](#示例-demo) · [全部参数](action-reference.md)\n\n${rewrite(guide, 'github-action.md')}\n\nAction 维护流程见 [独立仓库 README](https://github.com/wot-ui/ci-action#维护与发布)。\n`],
  ['action-reference.md', `# Action 参数参考\n\n${banner}\n\n${origin} 接入提示词、完整工作流和 Demo 见 [GitHub Action](github-action.md)。\n\n${rewrite(reference, 'action-reference.md')}\n`],
])
for (const [name, content] of files) {
  const file = path.join(root, 'docs/guides', name)
  if (check) {
    if (await readFile(file, 'utf8') !== content)
      throw new Error(`${name} is out of sync with ci-action README; run pnpm docs:action:sync and commit both generated pages`)
  }
  else {
    await writeFile(file, content)
  }
}
console.log(`Action docs ${check ? 'verified' : 'synced'}: ${files.size} pages, README sha256 ${digest.slice(0, 12)}`)
